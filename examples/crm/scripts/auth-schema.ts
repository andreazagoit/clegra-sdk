// Writes db/auth-schema.ts: the Drizzle tables better-auth needs for the
// options in lib/auth-options.ts, from better-auth's own Drizzle generator
// (what `npx @better-auth/cli generate` writes). Then `npm run db:generate`
// makes the migration. Run it again whenever a plugin there changes.
//
// The generator writes relations for Drizzle's relations v2 (drizzle-orm 1.x);
// this app is on drizzle-orm 0.45, and better-auth needs no relations, so
// they are left out.
import { writeFileSync } from "node:fs"

import { drizzleAdapter } from "@better-auth/drizzle-adapter/relations-v2"

import { authSchemaOptions } from "../lib/auth-options"

const file = new URL("../db/auth-schema.ts", import.meta.url)
const options = authSchemaOptions()
const adapter = drizzleAdapter({} as never, { provider: "pg" })(options)
if (!adapter.createSchema) throw new Error("This better-auth Drizzle adapter has no schema generator")
const { code } = await adapter.createSchema(options, file.pathname)
if (!code) throw new Error("better-auth generated no schema")

const relations = code.indexOf("export const authRelations")
const tables = (relations === -1 ? code : code.slice(0, relations)).replace(/^import \{ defineRelationsPart \} from "drizzle-orm";\n/m, "")
if (tables.includes("defineRelationsPart")) throw new Error("Unexpected generator output: relations are still in it")

writeFileSync(file, `// Generated by \`npm run auth:schema\` from lib/auth-options.ts. Do not edit.\n${tables.trimEnd()}\n`)
console.log(`wrote ${file.pathname}`)
